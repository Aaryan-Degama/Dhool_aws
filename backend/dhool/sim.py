"""Simulated neighbourhood: real weather through the physics, with known problems planted in code.

Never generated by an LLM. Every home's output follows the real sun and clouds; only the
losses (dust, washes, faults, haze, noise) are planted, and each day carries its true cause.
"""
import datetime
import json
import sys
from collections.abc import Callable
from typing import Any

import numpy as np
import pandas as pd

from . import config
from .expected import expected_daily_kwh, fetch_pm25, fetch_weather_with_forecast

# home index -> planted hardware problem; every other home only gets dust.
PLANTED = {0: "string_fault", 1: "string_fault", 2: "shading", 3: "inverter_trips"}


def simulate(weather: pd.DataFrame | Callable[[float, float], pd.DataFrame], pm25: pd.Series, n_homes: int = 30,
             seed: int = 0, hidden: bool = False, lat: float = config.SIM_LAT, lon: float = config.SIM_LON,
             dusty: int = 0, weather_noise: float = 0.0) -> dict[str, dict[str, Any]]:
    """Returns {home_id: {"meta": {...}, "daily": DataFrame[expected, actual, soiling, cause]}}.

    hidden=True is the test neighbourhood the rules are never tuned on: every setting the rules could have
    been fitted to is drawn afresh and wider (dust rates, noise, how much rain it takes to clean a roof,
    fault sizes and dates, which homes have a fault at all, haze strength), and readings go missing.

    dusty=N adds N homes after the others, beside a planted dust source (building work next door): dust settles
    several times faster and nobody washes them, so between rains they show the case Dhool is named after.
    They draw after the other homes, so those stay exactly as they were. Rain still cleans them: the weather is real.

    weather is one hourly frame for the whole neighbourhood, or a function (lat, lon) -> frame that gives each
    home its own. The demo data needs the second: the analysis fetches weather at each home's own spot, and a
    shower of 4.6 mm at one grid point and 5.2 mm at the next is the difference between a washed roof and not.

    weather_noise=0.15 makes the weather data wrong about the sun over each roof by about 15% a day, as gridded
    weather is over a real one: what the roof made is scaled by a random factor each day, and nothing else
    changes (expected output, the dust, the true cause). At 0 every home is exactly what it was without it.
    """
    rng = np.random.default_rng(seed)
    wild = np.random.default_rng([seed, 1])  # the hidden set's own draws, so the default homes never change
    cloud = np.random.default_rng([seed, 2])  # the weather error's own draws, for the same reason
    haze_per_100 = wild.uniform(0.06, 0.14) if hidden else 0.10
    local = weather if callable(weather) else lambda lat, lon: weather
    days = local(lat, lon)["rain"].resample("D").sum().index
    pm25 = pm25.reindex(days).fillna(0.0)
    # Haze dims every roof together: 10% lost per 100 µg/m³ above the threshold, at most 25%.
    haze = (1 - haze_per_100 * (pm25 - config.HAZE_PM25).clip(lower=0) / 100).clip(lower=0.75).to_numpy()

    homes: dict[str, dict[str, Any]] = {}
    for i in range(n_homes + dusty):
        meta: dict[str, Any] = {
            "id": f"home-{i:02d}",
            # To 2 decimals (about 1 km), as the API stores a home's location: the analysis must fetch weather
            # at the same spot this data was made from.
            "lat": round(lat + rng.uniform(-0.02, 0.02), 2),
            "lon": round(lon + rng.uniform(-0.02, 0.02), 2),
            "kw": float(rng.choice([1, 2, 3, 3, 5])),
            "tilt": round(rng.uniform(15, 25), 1),
            "azimuth": round(rng.uniform(160, 200), 1),
            "problem": PLANTED.get(i, "dust"),
        }
        here = local(meta["lat"], meta["lon"])
        rain = here["rain"].resample("D").sum()
        expected = expected_daily_kwh(here, meta["lat"], meta["lon"], meta["kw"], meta["tilt"], meta["azimuth"])

        # Dust builds at a steady daily rate; heavy rain or a wash resets it, light rain halves it.
        rate = rng.uniform(0.002, 0.005)
        washes = set(rng.choice(len(days), size=rng.integers(0, 4), replace=False))
        clean_mm = config.CLEAN_RAIN_MM
        if i >= n_homes:
            meta["problem"], rate, washes = "dust_source", rng.uniform(0.012, 0.016), set()
        if hidden:
            meta["problem"] = str(wild.choice(["dust", "string_fault", "shading", "inverter_trips"], p=[0.7, 0.12, 0.1, 0.08]))
            rate, clean_mm = wild.uniform(0.001, 0.008), wild.uniform(3, 10)
            washes = set(wild.choice(len(days), size=wild.integers(0, 7), replace=False))
        soiling, loss = np.zeros(len(days)), 0.0
        for d in range(len(days)):
            if rain.iloc[d] >= clean_mm or d in washes:
                loss = 0.0
            elif rain.iloc[d] >= 1.0:
                loss /= 2
            loss = min(loss + rate, 0.25)
            soiling[d] = loss

        hardware = np.ones(len(days))
        onset = int(rng.integers(len(days) // 3, 2 * len(days) // 3))
        fault, shade, trip_rate = None, 0.85, 0.05
        if hidden:
            onset = int(wild.integers(60, len(days) - 30))
            fault, shade, trip_rate = wild.uniform(0.4, 0.8), wild.uniform(0.78, 0.9), wild.uniform(0.03, 0.1)
        if meta["problem"] == "string_fault":      # one string dead from `onset`, never recovers
            hardware[onset:] = fault or rng.choice([0.5, 0.67])
        elif meta["problem"] == "shading":         # something new shades the roof from `onset`
            hardware[onset:] = shade
        elif meta["problem"] == "inverter_trips":  # shuts down for part of some days
            trips = (wild if hidden else rng).random(len(days)) < trip_rate
            hardware[trips] = (wild if hidden else rng).uniform(0.4, 0.7, trips.sum())

        baseline = rng.uniform(0.88, 0.96)  # wiring and panel quality: no home hits the physics number
        noise = rng.normal(1.0, 0.02, len(days))
        missing = np.zeros(len(days), bool)
        if hidden:
            baseline = wild.uniform(0.78, 0.98)
            noise = wild.normal(1.0, wild.uniform(0.01, 0.05), len(days))
            missing = wild.random(len(days)) < wild.uniform(0, 0.15)  # days the inverter never reported
        actual = expected.to_numpy() * baseline * (1 - soiling) * haze * hardware * noise
        if weather_noise:
            # ponytail: drawn afresh for every roof and every day. Real weather error is partly shared by
            # roofs a street apart and runs for days at a time; model that (one area-wide draw plus a smaller
            # one per roof, with some carry-over between days) if the neighbour comparison is ever scored on it.
            actual = actual * cloud.lognormal(0.0, weather_noise, len(days))
        actual[missing] = np.nan

        cause = np.select([hardware < 1, haze < 0.95, soiling > 0.05], ["fault", "haze", "dust"], "ok")
        meta["baseline"] = round(float(baseline), 3)
        meta["soiling_rate"] = round(float(rate), 4)
        meta["clean_mm"] = round(float(clean_mm), 1)
        meta["wash_days"] = sorted(str(days[d].date()) for d in washes)
        homes[meta["id"]] = {
            "meta": meta,
            "daily": pd.DataFrame(
                {"expected": expected.to_numpy().round(3), "actual": actual.round(3),
                 "soiling": soiling.round(4), "cause": cause},
                index=days,
            ),
        }
    return homes


def main(path: str = "data/neighbourhood.json", seed: int = 0) -> None:
    """Fetch 12 months of real weather, through yesterday, and write the neighbourhood to JSON.
    Run it again right before a demo: the demo inverter's last day is the day before this ran."""
    end = datetime.date.today() - datetime.timedelta(days=1)
    start = end - datetime.timedelta(days=365)
    # The archive lags about a week; the forecast API serves the recent days, as it does for the analysis.
    def weather(lat, lon):
        return fetch_weather_with_forecast(lat, lon, start).loc[:str(end)]
    pm25 = fetch_pm25(config.SIM_LAT, config.SIM_LON, str(start), str(end))
    homes = simulate(weather, pm25, seed=seed, dusty=3)  # the demo inverter's homes: three more, for the dust case
    out = {
        home_id: {"meta": h["meta"],
                  "daily": [{"date": str(day.date()), **row} for day, row in h["daily"].to_dict("index").items()]}
        for home_id, h in homes.items()
    }
    with open(path, "w") as f:
        json.dump(out, f)
    print(f"{len(homes)} homes, {start} to {end} -> {path}")


if __name__ == "__main__":
    main(*sys.argv[1:2])  # type: ignore[arg-type]  # one argument at most, the path: mypy cannot see the slice's length
